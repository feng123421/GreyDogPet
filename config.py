# --------------------------------------------------------------------------- #
# 三、素材路径
# --------------------------------------------------------------------------- #
def resource_root() -> Path:
    """返回资源根目录。

    PyInstaller 单文件模式会把 --add-data 的内容解压到临时目录 ``sys._MEIPASS``，
    因此需要优先读这个变量；源码运行时则以本文件所在目录为准。
    """
    bundled = getattr(sys, "_MEIPASS", None)
    if bundled:
        return Path(bundled)
    return Path(__file__).resolve().parent


ASSETS_DIR = resource_root() / "assets"   # 素材根路径

